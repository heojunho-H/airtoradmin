/** 대화 제목 — 첫 질문의 첫 줄 40자 */
export function titleFrom(message: string): string {
  const line = message.trim().split('\n')[0].trim();
  return line.length > 40 ? `${line.slice(0, 40)}…` : line || '새 대화';
}

